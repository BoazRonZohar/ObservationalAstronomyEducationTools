"""Build isochrones_PARSEC_UBV.csv.gz from raw CMD 3.9 output files.

Reads every raw/MH*_age*.dat(.gz) file downloaded from the CMD web interface
(PARSEC v1.2S + COLIBRI, UBVRIJHK Maiz-Apellaniz 2006 + Bessell 1990, Vega
mags, A_V = 0) and writes one compact table of (MH, logAge, label, Mini, MV, BV)
for the Cluster_CMD tool.
"""
import glob
import gzip
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(HERE, "raw")
OUT = os.path.join(HERE, "isochrones_PARSEC_UBV.csv.gz")

LABELS_KEPT = range(1, 8)   # 1 MS ... 7 early AGB
MV_LIMIT = 12.0
MIN_STEP = 0.01             # mag, in the (BV, MV) plane


def open_any(path):
    return gzip.open(path, "rt") if path.endswith(".gz") else open(path)


def read_raw(path):
    """Yield (MH, logAge, label, Mini, Bmag, Vmag) in file order, plus header lines."""
    header, rows, cols = [], [], None
    with open_any(path) as f:
        for line in f:
            if line.startswith("#"):
                if "Zini" in line and "Vmag" in line:
                    cols = line[1:].split()
                elif cols is None:
                    header.append(line.rstrip("\n"))
                continue
            p = line.split()
            if not p or cols is None:
                continue
            d = dict(zip(cols, p))
            rows.append((float(d["MH"]), float(d["logAge"]), int(d["label"]),
                         float(d["Mini"]), float(d["Bmag"]), float(d["Vmag"])))
    return header, rows


def thin(points):
    """points: list of (label, Mini, MV, BV) for one isochrone, already filtered."""
    kept = []
    n = len(points)
    for i, (lab, mini, mv, bv) in enumerate(points):
        first_of_run = i == 0 or points[i - 1][0] != lab
        last_of_run = i == n - 1 or points[i + 1][0] != lab
        if first_of_run or last_of_run or not kept:
            kept.append(points[i])
            continue
        _, _, kmv, kbv = kept[-1]
        if ((mv - kmv) ** 2 + (bv - kbv) ** 2) ** 0.5 >= MIN_STEP:
            kept.append(points[i])
    return kept


def main():
    files = sorted(f for f in glob.glob(os.path.join(RAW, "MH*_age*.dat*")))
    if not files:
        raise SystemExit("no raw files in " + RAW)
    isochrones = {}   # (MH, logAge) -> list of rows in CMD order
    cmd_header = None
    for path in files:
        header, rows = read_raw(path)
        cmd_header = cmd_header or header
        for mh, age, lab, mini, b, v in rows:
            key = (round(mh, 3), round(age, 3))
            isochrones.setdefault(key, []).append((lab, mini, v, b - v))

    out_rows = []
    for key in sorted(isochrones):
        pts = [p for p in isochrones[key] if p[0] in LABELS_KEPT and p[2] <= MV_LIMIT]
        for lab, mini, mv, bv in thin(pts):
            out_rows.append("%.3f,%.3f,%d,%s,%.3f,%.3f" % (
                key[0], key[1], lab, "%.5g" % mini, mv, bv))

    mhs = sorted({k[0] for k in isochrones})
    ages = sorted({k[1] for k in isochrones})
    gen = next((h for h in cmd_header if "File generated by" in h), "")
    date = re.search(r" on (.*)$", gen)
    refs = next((h for h in cmd_header if "Basic references" in h), "#").lstrip("# ")
    comments = [
        "PARSEC isochrones in Johnson B and V for Cluster_CMD",
        "Source: CMD 3.9 web interface, https://stev.oapd.inaf.it/cgi-bin/cmd",
        "Tracks: PARSEC v1.2S + COLIBRI S_37 + S_35 + PR16 (default COLIBRI choice); Reimers eta = 0.2 on the RGB",
        "Photometric system: UBVRIJHK (cf. Maiz-Apellaniz 2006 + Bessell 1990), Vega magnitudes, YBC + new Vega bolometric corrections (Chen et al. 2019)",
        "No circumstellar dust; interstellar extinction A_V = 0; IMF Kroupa (2001, 2002) canonical (default)",
        "Download date (CMD timestamp of first file): " + (date.group(1) if date else "unknown"),
        "Grid: [M/H] = " + " ".join("%.2f" % m for m in mhs),
        "Grid: log(age/yr) = %.2f..%.2f, step 0.1 below 8.0 and 0.02 from 8.0 (%d ages)" % (ages[0], ages[-1], len(ages)),
        "Kept: labels 1-7 (MS to early AGB; dropped 0 PMS, 8 TP-AGB, 9 post-AGB) and MV <= 12",
        "Thinning: first and last point of each run of equal label always kept; otherwise a point is kept",
        "  only if it is at least 0.01 mag from the last kept point in the (BV, MV) plane",
        "Columns: MH = [M/H]; logAge = log10(age/yr); label = PARSEC evolutionary stage;",
        "  Mini = initial mass (Msun); MV = absolute V mag; BV = B - V",
        "Please cite (as requested by CMD): " + refs,
        "  and for the bolometric corrections: Chen et al. (2019), A&A, 632, A105",
    ]
    with gzip.open(OUT, "wt", newline="\n") as f:
        for c in comments:
            f.write("# " + c + "\n")
        f.write("MH,logAge,label,Mini,MV,BV\n")
        f.write("\n".join(out_rows) + "\n")
    print("wrote", OUT, len(isochrones), "isochrones,", len(out_rows), "rows")


if __name__ == "__main__":
    main()
